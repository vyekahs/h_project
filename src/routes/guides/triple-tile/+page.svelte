			<section id="intro">
				<h2>트리플 타일이란?</h2>
				<p>
					트리플 타일(Triple Tile)은 마작 솔리테어에서 영감을 받은 매칭 퍼즐 게임입니다.
					쌓여 있는 타일들 중에서 같은 무늬의 타일 3개를 모아 제거하여 모든 타일을 없애는 것이 목표입니다.
					"3 타일(3 Tiles)", "타일 매치", "마작 매칭" 등의 이름으로도 알려져 있습니다.
				</p>
				<p>
					간단한 규칙과 귀여운 비주얼로 캐주얼하게 즐길 수 있지만,
					타일이 겹쳐 쌓여 있어 무계획적으로 선택하면 금세 막히게 됩니다.
					어떤 타일을 먼저 선택할지 전략적으로 판단하는 것이 중요합니다.
				</p>
			</section>

			<section id="rules">
				<h2>기본 규칙</h2>
				<ol>
					<li>화면에 여러 겹으로 쌓인 타일이 배치되어 있습니다.</li>
					<li>다른 타일에 가려지지 않은(선택 가능한) 타일만 고를 수 있습니다.</li>
					<li>선택한 타일은 하단 슬롯(최대 7칸)에 들어갑니다.</li>
					<li><strong>슬롯에 같은 타일이 3개 모이면</strong> 자동으로 제거됩니다.</li>
					<li>모든 타일을 제거하면 클리어, 슬롯이 7칸 다 차면 게임 오버입니다.</li>
				</ol>
				<div class="info-box">
					<strong>핵심</strong>: 슬롯이 가득 차지 않도록 관리하면서, 같은 타일 3개를 빠르게 모으는 것이 관건입니다.
					슬롯에 서로 다른 타일이 6종류 이상 쌓이면 위험합니다.
				</div>
			</section>

			<section id="strategy">
				<h2>풀이 전략</h2>
				<h3>1. 슬롯 관리가 최우선입니다</h3>
				<p>
					게임 오버의 유일한 조건은 슬롯이 가득 차는 것입니다.
					항상 슬롯에 빈 칸을 2~3개 유지하는 것을 목표로 하세요.
					무작정 타일을 선택하면 슬롯이 다양한 종류의 타일로 채워져 빠르게 막힙니다.
				</p>

				<h3>2. 3개를 완성할 수 있을 때만 선택하세요</h3>
				<p>
					새로운 종류의 타일을 선택하기 전에, 같은 타일이 3개 보이는지 확인하세요.
					2개만 보이는 상태에서 선택하면 슬롯을 차지한 채 세 번째를 기다리게 되어 비효율적입니다.
					가능한 한 3개가 모두 선택 가능한 상태일 때 진행하세요.
				</p>

				<h3>3. 위층 타일을 우선 제거하세요</h3>
				<p>
					겹쳐 쌓인 타일 구조에서, 위층의 타일을 먼저 제거해야 아래층 타일이 드러납니다.
					아래층에 필요한 타일이 숨겨져 있을 수 있으므로,
					위층부터 정리하면 선택지가 늘어나 유리합니다.
				</p>

				<h3>4. 셔플 기능을 전략적으로 사용하세요</h3>
				<p>
					정말 막혔을 때는 셔플(타일 섞기) 기능을 사용할 수 있습니다.
					단, 셔플은 횟수 제한이 있고 점수에서 감점되므로,
					정말 다른 방법이 없을 때만 사용하세요.
				</p>
			</section>

			<section id="tips">
				<h2>실전 팁</h2>
				<h3>1. 먼저 전체 판을 스캔하세요</h3>
				<p>
					게임 시작 시 바로 타일을 선택하지 말고, 먼저 어떤 타일이 어디에 있는지 전체적으로 파악하세요.
					같은 종류의 타일 위치를 미리 알면 효율적인 순서를 계획할 수 있습니다.
				</p>
				<h3>2. 가장 많이 보이는 타일부터 처리하세요</h3>
				<p>
					선택 가능한 타일 중 같은 종류가 3개 이상 보이면 가장 안전한 선택입니다.
					즉시 제거할 수 있으므로 슬롯을 차지하지 않습니다.
				</p>
				<h3>3. 슬롯의 타일 구성을 항상 확인하세요</h3>
				<p>
					슬롯에 이미 2개 있는 타일은 1개만 더 찾으면 제거되므로 우선적으로 찾아보세요.
					슬롯에 1개만 있는 타일은 2개를 더 찾아야 하므로 급하지 않다면 후순위로 미루세요.
				</p>
				<h3>4. 시간보다 정확성에 집중하세요</h3>
				<p>
					빠르게 터치하다가 실수로 원치 않는 타일을 선택하면 상황이 나빠질 수 있습니다.
					속도보다는 올바른 선택에 집중하세요. 점수는 시간뿐 아니라 셔플 사용 횟수도 반영됩니다.
				</p>
			</section>

